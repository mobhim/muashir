# Download the site's typefaces from Google Fonts and write fonts.css next to them.
# Both are licensed under the SIL Open Font License.
#   powershell -ExecutionPolicy Bypass -File site\fonts\fetch_fonts.ps1
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$ua = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36'
$api = 'https://fonts.googleapis.com/css2?family=Alexandria:wght@400;600;800&family=IBM+Plex+Sans+Arabic:wght@400;500;600&display=swap'

function Get-WithRetry([string]$url, [string]$outFile) {
    for ($i = 1; $i -le 6; $i++) {
        try {
            if ($outFile) { Invoke-WebRequest -Uri $url -UserAgent $ua -OutFile $outFile -UseBasicParsing; return }
            return (Invoke-WebRequest -Uri $url -UserAgent $ua -UseBasicParsing).Content
        } catch { if ($i -eq 6) { throw }; Start-Sleep -Seconds (2 * $i) }
    }
}

$css = Get-WithRetry $api $null
$keep = 'arabic', 'latin', 'latin-ext', 'math', 'symbols'
$blocks = [regex]::Matches($css, '/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]+\})')
$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('/* Self-hosted copies of Alexandria and IBM Plex Sans Arabic (SIL Open Font License). Generated by fetch_fonts.ps1. */')
$done = @{}
foreach ($b in $blocks) {
    $subset = $b.Groups[1].Value
    if ($keep -notcontains $subset) { continue }
    $face = $b.Groups[2].Value
    $family = ([regex]::Match($face, "font-family:\s*'([^']+)'")).Groups[1].Value
    $weight = ([regex]::Match($face, 'font-weight:\s*([\d ]+)')).Groups[1].Value.Trim() -replace ' ', '-'
    $url = ([regex]::Match($face, 'url\((https://[^)]+\.woff2)\)')).Groups[1].Value
    if (-not $url) { continue }
    # variable fonts serve one file for several weights: download each distinct URL once
    if (-not $done.ContainsKey($url)) {
        $name = (($family -replace ' ', '') + '-' + $subset + '-' + $done.Count + '.woff2').ToLower()
        Get-WithRetry $url (Join-Path $here $name)
        $done[$url] = $name
    }
    [void]$out.AppendLine($face.Replace($url, $done[$url]))
}
[IO.File]::WriteAllText((Join-Path $here 'fonts.css'), $out.ToString(), (New-Object Text.UTF8Encoding($false)))
"faces written: $(([regex]::Matches($out.ToString(), '@font-face')).Count); files: $($done.Count)"
Get-ChildItem $here -Filter *.woff2 | ForEach-Object { '{0,-40} {1,7:N0} bytes' -f $_.Name, $_.Length }
